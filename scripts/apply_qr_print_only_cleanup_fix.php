CSS;
writeFileEnsured($root . '/public/css/document-qr-print-only-cleanup.css', $css);

$js = <<<'JS'
(function () {
    function closestBox(el) {
        return el.closest('.da-qr-print-fixed, .da-print-qr, .document-print-qr, .document-qr-card, .qr-print-card, .qr-card, .da-qr-card, .card, .panel, div') || el;
    }

    function cleanupNormalShowPage() {
        var path = window.location.pathname || '';
        var isDocumentShow = /^\/documents\/\d+\/?$/.test(path);
        if (!isDocumentShow) return;

        document.body.classList.add('da-document-show-page');

        var selectors = [
            '.da-qr-print-fixed',
            '.da-print-qr',
            '.document-print-qr',
            '.qr-print-card',
            '.document-qr-card',
            '[data-da-print-qr="1"]',
            'img[src*="/qr.svg"]',
            'img[src*="qr.svg"]',
            'iframe[src*="/qr.svg"]'
        ];

        var nodes = [];
        selectors.forEach(function (sel) {
            document.querySelectorAll(sel).forEach(function (node) {
                if (nodes.indexOf(node) === -1) nodes.push(node);
            });
        });

        nodes.forEach(function (node) {
            var box = closestBox(node);
            box.classList.add('da-hidden-normal-show-qr');
            box.style.display = 'none';
        });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', cleanupNormalShowPage);
    } else {
        cleanupNormalShowPage();
    }
})();
JS;
writeFileEnsured($root . '/public/js/document-qr-print-only-cleanup.js', $js);

$partial = <<<'BLADE'
{{-- QR print position partial - controlled from /settings/qr-print-position --}}
@php
    use Illuminate\Support\Facades\DB;
    use Illuminate\Support\Facades\Route;

    $daQrDocument = $document ?? $book ?? $documentModel ?? $item ?? null;

    $daQrSettings = [];
    try {
        if (\Illuminate\Support\Facades\Schema::hasTable('qr_print_settings')) {
            $daQrSettings = DB::table('qr_print_settings')->pluck('value', 'key')->toArray();
        }
    } catch (\Throwable $e) {
        $daQrSettings = [];
    }

    $daQrEnabled = filter_var($daQrSettings['enabled'] ?? $daQrSettings['show_qr'] ?? true, FILTER_VALIDATE_BOOLEAN);
    $daQrShowLabel = filter_var($daQrSettings['show_label'] ?? $daQrSettings['label_enabled'] ?? true, FILTER_VALIDATE_BOOLEAN);

    $daQrX = is_numeric($daQrSettings['x'] ?? null) ? (float) $daQrSettings['x'] : 55;
    $daQrY = is_numeric($daQrSettings['y'] ?? null) ? (float) $daQrSettings['y'] : 48;
    $daQrSize = is_numeric($daQrSettings['size'] ?? null) ? (float) $daQrSettings['size'] : 16;
    $daQrPadding = is_numeric($daQrSettings['padding'] ?? null) ? (float) $daQrSettings['padding'] : 1;
    $daQrLabelSize = is_numeric($daQrSettings['label_size'] ?? null) ? (float) $daQrSettings['label_size'] : 2.2;

    $daQrId = is_object($daQrDocument) ? ($daQrDocument->id ?? null) : null;
    $daQrRouteName = Route::has('documents.qr') ? 'documents.qr' : (Route::has('documents.qr.svg') ? 'documents.qr.svg' : null);
@endphp

@if($daQrEnabled && $daQrId && $daQrRouteName)
    <div class="da-qr-print-fixed" data-da-print-qr="1"
         style="left: {{ $daQrX }}mm; top: {{ $daQrY }}mm; width: {{ $daQrSize + ($daQrPadding * 2) }}mm; padding: {{ $daQrPadding }}mm;">
        <img src="{{ route($daQrRouteName, $daQrId) }}" alt="QR">
        @if($daQrShowLabel)
            <span class="da-qr-print-label" style="font-size: {{ $daQrLabelSize }}mm;">رمز الوصول الإلكتروني</span>
        @endif
    </div>
@endif
BLADE;
writeFileEnsured($root . '/resources/views/documents/partials/qr-print-position.blade.php', $partial);

// Load CSS/JS in main layout.
$layoutCandidates = [
    $root . '/resources/views/layouts/app.blade.php',
    $root . '/resources/views/layouts/admin.blade.php',
    $root . '/resources/views/layouts/main.blade.php',
];
foreach ($layoutCandidates as $layout) {
    if (!file_exists($layout)) continue;
    $link = "<link rel=\"stylesheet\" href=\"{{ asset('css/document-qr-print-only-cleanup.css') }}\">";
    $script = "<script src=\"{{ asset('js/document-qr-print-only-cleanup.js') }}\" defer></script>";
    injectOnce($layout, '</head>', $link);
    injectOnce($layout, '</body>', $script, $script);
}

// Include partial inside print-related document blade files.
$include = "@include('documents.partials.qr-print-position', ['document' => \$document ?? \$book ?? null])";
$updatedPrints = 0;
foreach (findPrintBlades($root) as $blade) {
    $content = file_get_contents($blade);
    if (str_contains($content, "documents.partials.qr-print-position")) {
        $updatedPrints++;
        continue;
    }
    if (str_contains($content, '</body>')) {
        $content = str_replace('</body>', $include . "\n</body>", $content);
    } else {
        $content .= "\n" . $include . "\n";
    }
    file_put_contents($blade, $content);
    $updatedPrints++;
}

if ($updatedPrints === 0) {
    fwrite(STDERR, "WARNING: لم يتم العثور على ملف طباعة داخل resources/views/documents يحتوي print/reference. قد تحتاج تزويدي باسم ملف الطباعة.\n");
}

echo "DONE: تم تنظيف ظهور QR في صفحة العرض وربط QR بملف جزئي خاص بالطباعة فقط. ملفات الطباعة المعدلة: {$updatedPrints}\n";
echo "NEXT: php artisan view:clear && php artisan optimize:clear && php scripts/check_qr_print_only_cleanup_fix.php\n";
