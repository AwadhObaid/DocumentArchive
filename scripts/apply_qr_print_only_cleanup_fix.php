<?php

/**
 * QR print-only cleanup fix for DocumentArchive.
 * - Prevents print-position QR from appearing/floating inside the normal document show page.
 * - Provides a single shared print-position partial for print pages.
 * - Loads a small CSS/JS cleanup layer safely.
 */

$root = realpath(__DIR__ . '/..');
if (!$root || !file_exists($root . DIRECTORY_SEPARATOR . 'artisan')) {
    fwrite(STDERR, "ERROR: شغّل السكربت من جذر مشروع Laravel: php scripts/apply_qr_print_only_cleanup_fix.php\n");
    exit(1);
}

function writeFileEnsured(string $path, string $content): void {
    $dir = dirname($path);
    if (!is_dir($dir)) {
        mkdir($dir, 0777, true);
    }
    file_put_contents($path, $content);
}

function removeBackupDirs(string $base): void {
    if (!is_dir($base)) return;
    $it = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($base, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST
    );
    foreach ($it as $item) {
        if ($item->isDir() && str_starts_with($item->getFilename(), '_backup')) {
            $dir = $item->getPathname();
            $rit = new RecursiveIteratorIterator(
                new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
                RecursiveIteratorIterator::CHILD_FIRST
            );
            foreach ($rit as $sub) {
                $sub->isDir() ? @rmdir($sub->getPathname()) : @unlink($sub->getPathname());
            }
            @rmdir($dir);
        }
    }
}

function injectOnce(string $file, string $needle, string $insert, string $fallbackAppend = ''): bool {
    if (!file_exists($file)) return false;
    $content = file_get_contents($file);
    if (str_contains($content, $insert) || str_contains($content, trim($insert))) return true;
    if (str_contains($content, $needle)) {
        $content = str_replace($needle, $insert . "\n" . $needle, $content);
        file_put_contents($file, $content);
        return true;
    }
    if ($fallbackAppend !== '') {
        file_put_contents($file, $content . "\n" . $fallbackAppend . "\n");
        return true;
    }
    return false;
}

function findPrintBlades(string $root): array {
    $dir = $root . DIRECTORY_SEPARATOR . 'resources' . DIRECTORY_SEPARATOR . 'views' . DIRECTORY_SEPARATOR . 'documents';
    if (!is_dir($dir)) return [];
    $files = [];
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
    foreach ($it as $file) {
        if (!$file->isFile()) continue;
        $path = $file->getPathname();
        $name = strtolower($file->getFilename());
        $rel = str_replace($root . DIRECTORY_SEPARATOR, '', $path);
        if (str_contains($rel, '_backup')) continue;
        if (str_ends_with($name, '.blade.php') && (str_contains($name, 'print') || str_contains($name, 'reference'))) {
            $files[] = $path;
        }
    }
    return $files;
}

removeBackupDirs($root . DIRECTORY_SEPARATOR . 'app');
removeBackupDirs($root . DIRECTORY_SEPARATOR . 'resources');
removeBackupDirs($root . DIRECTORY_SEPARATOR . 'routes');

$css = <<<'CSS'
/* QR cleanup and print positioning - generated by apply_qr_print_only_cleanup_fix.php */
.da-qr-print-fixed {
    position: absolute !important;
    z-index: 20;
    box-sizing: border-box;
    text-align: center;
    direction: rtl;
    background: #fff;
    border: 0.25mm solid #d9dee8;
    border-radius: 1.5mm;
    line-height: 1.15;
    overflow: hidden;
}
.da-qr-print-fixed img,
.da-qr-print-fixed svg {
    display: block;
    width: 100% !important;
    height: auto !important;
    margin: 0 auto;
}
.da-qr-print-label {
    display: block;
    color: #6b7280;
    white-space: nowrap;
    margin-top: 1mm;
